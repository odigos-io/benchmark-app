-- Three tables, split by lifecycle so the cost of every statement is a function of the data and
-- not of how many arms the database has already served.
--
--   customers    static, 1,024 rows, primary-key point reads only
--   order_lookup static, 10,000 rows, index range scans only
--   orders       bounded ring of BENCH_RING_SLOTS rows, pre-filled by StateService at startup,
--                touched only by INSERT ... ON CONFLICT (slot) DO UPDATE
--
-- The ring has no secondary index on the updated columns so every upsert is a HOT update that
-- stays inside the page (fillfactor 70 leaves the room). Dead versions are pruned in-page and by
-- an autovacuum that fires on an absolute dead-tuple count with the cost limiter off.

CREATE TABLE IF NOT EXISTS customers (
    id INTEGER PRIMARY KEY,
    name VARCHAR(64) NOT NULL,
    tier VARCHAR(16) NOT NULL,
    email VARCHAR(128) NOT NULL,
    credit_limit NUMERIC(12, 2) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

INSERT INTO customers (id, name, tier, email, credit_limit, created_at)
SELECT
    g,
    'cust-' || g,
    CASE WHEN g % 3 = 0 THEN 'gold' ELSE 'silver' END,
    'cust-' || g || '@example.com',
    ((g % 900) + 100)::numeric,
    TIMESTAMP WITH TIME ZONE '2026-01-01 00:00:00+00' + (g * INTERVAL '1 minute')
FROM generate_series(0, 1023) AS g
ON CONFLICT (id) DO NOTHING;

CREATE TABLE IF NOT EXISTS order_lookup (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id VARCHAR(64) NOT NULL UNIQUE,
    customer_id VARCHAR(64) NOT NULL,
    product VARCHAR(64) NOT NULL,
    quantity INTEGER NOT NULL,
    amount NUMERIC(12, 2) NOT NULL,
    active BOOLEAN NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_order_lookup_customer_created
    ON order_lookup (customer_id, created_at DESC);

-- customer_id spans cust-0..cust-1023, so each range scan matches ~9 rows and LIMIT 5 does work.
-- Every predicate of the six-bind query is satisfied by construction.
INSERT INTO order_lookup (order_id, customer_id, product, quantity, amount, active, created_at)
SELECT
    'lk-' || g,
    'cust-' || (g % 1024),
    'widget',
    1 + (g % 9),
    ((g % 9999) + 1)::numeric / 100,
    TRUE,
    TIMESTAMP WITH TIME ZONE '2026-01-01 00:00:00+00' + (g * INTERVAL '1 second')
FROM generate_series(0, 9999) AS g
WHERE NOT EXISTS (SELECT 1 FROM order_lookup)
ON CONFLICT (order_id) DO NOTHING;

CREATE TABLE IF NOT EXISTS orders (
    slot BIGINT PRIMARY KEY,
    customer_id VARCHAR(64) NOT NULL,
    order_ref VARCHAR(64) NOT NULL,
    amount NUMERIC(12, 2) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0
) WITH (fillfactor = 70);

ALTER TABLE orders SET (
